// Renders every MyVault icon from the single logo source, VaultMarkPainter
// (lib/core/brand/vault_mark.dart): Android launcher icons (legacy, round, adaptive layers,
// themed/monochrome), the pre-Android-12 splash logo, iOS app icons, web icons, the Play
// Store icon and SVG masters.
//
// Run from the project root after changing the logo:
//   flutter test tool/generate_app_icons.dart
// then strip the alpha channel from the iOS icons (App Store requirement):
//   python tool/flatten_ios_icons.py
import 'dart:io';
import 'dart:ui' as ui;

import 'package:flutter/material.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:myvault/core/brand/vault_mark.dart';

Future<void> _render(String path, int px, VaultMarkPainter painter) async {
  final recorder = ui.PictureRecorder();
  painter.paint(Canvas(recorder), Size(px.toDouble(), px.toDouble()));
  final image = await recorder.endRecording().toImage(px, px);
  final png = await image.toByteData(format: ui.ImageByteFormat.png);
  image.dispose();
  final file = File(path);
  await file.parent.create(recursive: true);
  await file.writeAsBytes(png!.buffer.asUint8List());
}

/// Android density buckets and their scale relative to mdpi.
const _densities = {'mdpi': 1.0, 'hdpi': 1.5, 'xhdpi': 2.0, 'xxhdpi': 3.0, 'xxxhdpi': 4.0};

// Shield height as a fraction of each canvas.
const double _legacyMark = 0.56; // inside the 92% tile
const double _roundMark = 0.52;
const double _adaptiveMark = 0.42; // 45dp of the 108dp layer: well inside the 66dp safe zone
const double _fullBleedMark = 0.58;
const double _maskableMark = 0.44; // web maskable safe zone is the central 80% circle

String _svgPath(List<(String, List<double>)> commands, {double scale = 1, double dx = 0, double dy = 0}) {
  String n(double v) => v.toStringAsFixed(2).replaceFirst(RegExp(r'\.?0+$'), '');
  final out = StringBuffer();
  for (final (op, v) in commands) {
    out.write(op);
    for (var i = 0; i < v.length; i += 2) {
      out.write('${i == 0 ? '' : ' '}${n(v[i] * scale + dx)} ${n(v[i + 1] * scale + dy)}');
    }
  }
  return out.toString();
}

String _hex(Color c) => '#${(c.toARGB32() & 0xFFFFFF).toRadixString(16).padLeft(6, '0').toUpperCase()}';

/// SVG of the logo on its rounded tile (1024 x 1024), or of the mark alone.
String _svg({required bool tile}) {
  const size = 1024.0;
  final markHeight = size * (tile ? _legacyMark : 0.9);
  final k = markHeight / 90.6;
  final dx = size / 2 - 50 * k;
  final dy = size / 2 - 50.3 * k;
  final shield = _svgPath(VaultMarkPainter.shieldCommands, scale: k, dx: dx, dy: dy);
  final slot = _svgPath(VaultMarkPainter.keyholeSlotCommands, scale: k, dx: dx, dy: dy);
  final cx = VaultMarkPainter.keyholeCx * k + dx;
  final cy = VaultMarkPainter.keyholeCy * k + dy;
  final r = VaultMarkPainter.keyholeR * k;
  const tileSide = size * 0.92;
  const tileOrigin = (size - tileSide) / 2;
  return '''<?xml version="1.0" encoding="UTF-8"?>
<!-- MyVault logo. Generated by tool/generate_app_icons.dart from lib/core/brand/vault_mark.dart. -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024" width="1024" height="1024">
  <defs>
    <linearGradient id="brand" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="${_hex(VaultMarkPainter.gradientStart)}"/>
      <stop offset="1" stop-color="${_hex(VaultMarkPainter.gradientEnd)}"/>
    </linearGradient>
    <linearGradient id="keyhole" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="${_hex(VaultMarkPainter.keyholeTop)}"/>
      <stop offset="1" stop-color="${_hex(VaultMarkPainter.keyholeBottom)}"/>
    </linearGradient>
    <clipPath id="shield"><path d="$shield"/></clipPath>
  </defs>
${tile ? '  <rect x="$tileOrigin" y="$tileOrigin" width="$tileSide" height="$tileSide" rx="${tileSide * 0.225}" fill="url(#brand)"/>\n' : ''}  <g clip-path="url(#shield)">
    <rect x="0" y="0" width="${size / 2}" height="$size" fill="${_hex(VaultMarkPainter.shieldLight)}"/>
    <rect x="${size / 2}" y="0" width="${size / 2}" height="$size" fill="${_hex(VaultMarkPainter.shieldShade)}"/>
  </g>
  <circle cx="$cx" cy="$cy" r="$r" fill="url(#keyhole)"/>
  <path d="$slot" fill="url(#keyhole)"/>
</svg>
''';
}

void main() {
  TestWidgetsFlutterBinding.ensureInitialized();

  test('generate app icons', () async {
    const res = 'android/app/src/main/res';
    for (final MapEntry(key: bucket, value: scale) in _densities.entries) {
      final legacy = (48 * scale).round();
      final layer = (108 * scale).round();
      final splash = (112 * scale).round();
      await _render('$res/mipmap-$bucket/ic_launcher.png', legacy,
          VaultMarkPainter(background: VaultMarkBackground.roundedTile, markScale: _legacyMark, shadow: legacy >= 72));
      await _render('$res/mipmap-$bucket/ic_launcher_round.png', legacy,
          VaultMarkPainter(background: VaultMarkBackground.circle, markScale: _roundMark, shadow: legacy >= 72));
      await _render('$res/mipmap-$bucket/ic_launcher_foreground.png', layer,
          const VaultMarkPainter(markScale: _adaptiveMark));
      await _render('$res/mipmap-$bucket/ic_launcher_background.png', layer,
          const VaultMarkPainter(background: VaultMarkBackground.fullBleed, drawMark: false));
      await _render('$res/mipmap-$bucket/ic_launcher_monochrome.png', layer,
          const VaultMarkPainter(markScale: _adaptiveMark, monochrome: true));
      await _render('$res/drawable-$bucket/launch_logo.png', splash,
          const VaultMarkPainter(background: VaultMarkBackground.roundedTile, markScale: _legacyMark));
    }

    // iOS: full-bleed squares (iOS applies its own corner mask).
    const ios = 'ios/Runner/Assets.xcassets/AppIcon.appiconset';
    const iosIcons = {
      'Icon-App-20x20@1x.png': 20, 'Icon-App-20x20@2x.png': 40, 'Icon-App-20x20@3x.png': 60,
      'Icon-App-29x29@1x.png': 29, 'Icon-App-29x29@2x.png': 58, 'Icon-App-29x29@3x.png': 87,
      'Icon-App-40x40@1x.png': 40, 'Icon-App-40x40@2x.png': 80, 'Icon-App-40x40@3x.png': 120,
      'Icon-App-60x60@2x.png': 120, 'Icon-App-60x60@3x.png': 180,
      'Icon-App-76x76@1x.png': 76, 'Icon-App-76x76@2x.png': 152,
      'Icon-App-83.5x83.5@2x.png': 167, 'Icon-App-1024x1024@1x.png': 1024,
    };
    for (final MapEntry(key: name, value: px) in iosIcons.entries) {
      await _render('$ios/$name', px,
          VaultMarkPainter(background: VaultMarkBackground.fullBleed, markScale: _fullBleedMark, shadow: px >= 60));
    }

    // Web.
    await _render('web/favicon.png', 32,
        const VaultMarkPainter(background: VaultMarkBackground.roundedTile, markScale: 0.6, shadow: false));
    for (final px in [192, 512]) {
      await _render('web/icons/Icon-$px.png', px,
          const VaultMarkPainter(background: VaultMarkBackground.roundedTile, markScale: _legacyMark));
      await _render('web/icons/Icon-maskable-$px.png', px,
          const VaultMarkPainter(background: VaultMarkBackground.fullBleed, markScale: _maskableMark));
    }

    // Brand masters.
    await _render('branding/myvault_icon_1024.png', 1024,
        const VaultMarkPainter(background: VaultMarkBackground.roundedTile, markScale: _legacyMark));
    await _render('branding/play_store_icon_512.png', 512,
        const VaultMarkPainter(background: VaultMarkBackground.fullBleed, markScale: _fullBleedMark));
    await File('branding/myvault_logo.svg').writeAsString(_svg(tile: true));
    await File('branding/myvault_mark.svg').writeAsString(_svg(tile: false));
  });
}
